const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const books = JSON.parse(fs.readFileSync(path.join(root, 'wordbooks/manifest.json'), 'utf8'));
const chapter = books.find(book => book.id === 'custom-unit-11');
assert.ok(chapter, 'Unit 11 must be listed');
assert.equal(chapter.cardCount, 60);
const ctx = vm.createContext({document:{querySelector:()=>({addEventListener(){}})},localStorage:{getItem:()=>null}});
vm.runInContext(fs.readFileSync(path.join(root,'app.js'),'utf8').replace(/let state = loadState\(\);/, 'let state = createDefaultState();').replace(/loadVoices\(\);\s*syncCountPicker\(\);\s*loadVocabulary\(\);\s*$/, ''),ctx);
ctx.text=fs.readFileSync(path.join(root,chapter.url),'utf8');
const words=vm.runInContext('parseVocabulary(text)',ctx);
assert.equal(words.length,60);
assert.equal(new Set(words.map(w=>w.id)).size,60);
assert.ok(words.every(w=>w.meaning && w.meaningZh && w.example && w.translation && w.translationZh));
assert.equal(words.find(w=>w.id==='anschliessend').imagePath,'');
assert.equal(words.find(w=>w.id==='luegen').imagePath,'assets/vocab-images/custom-luegen-schritte-plus-b12-unit11-new-scene-v4.png');
const map=new Map(JSON.parse(fs.readFileSync(path.join(root,'assets/vocab-images/manifest.json'),'utf8')).filter(x=>typeof x==='object').map(x=>[x.id,x.file]));
const withImages=words.filter(w=>w.imagePath);assert.equal(withImages.length,59);
const hashes=new Set();for(const w of withImages){const file=w.imagePath.split('/').pop();assert.equal(map.get('custom-unit11-'+w.id),file,w.id);const bytes=fs.readFileSync(path.join(root,w.imagePath));assert.equal(bytes.readUInt32BE(16),bytes.readUInt32BE(20),w.id);assert.ok(bytes.readUInt32BE(16)>=1024,w.id);hashes.add(crypto.createHash('sha256').update(bytes).digest('hex'));}assert.equal(hashes.size,59);
console.log('Unit 11: 60 bilingual cards, 59 unique images and one text-only card passed.');
